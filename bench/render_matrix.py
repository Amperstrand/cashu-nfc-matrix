#!/usr/bin/env python3
"""Render the wallet matrix (refactor 3) from results/*.jsonl evidence.

Reads every results/payment-soak-*.jsonl and emits results/MATRIX.md — a
per-(wallet, reader) table of what has been PROVEN, with evidence links.
Hand-edited matrix rows are retired: the README block is regenerated from
the same data with --readme.

Usage:
  python3 bench/render_matrix.py               # results/MATRIX.md
  python3 bench/render_matrix.py --readme      # + refresh README block

Deterministic, offline, no hardware.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
RESULTS = REPO / "results"
README = REPO / "README.md"

READER_FOR = {
    "Nucula": "nucula/PN7160",
    "ACR": "ACR1252",
    "M5stick": "m5stick/MFRC522",
}


def _reader_key(subst: str) -> str:
    for k, v in READER_FOR.items():
        if subst.startswith(k):
            return v
    return subst


def collect() -> dict[tuple[str, str], dict]:
    """cells[(wallet, reader)] -> {ok, fail, evidence:[files]}"""
    cells: dict[tuple[str, str], dict] = {}
    for f in sorted(RESULTS.glob("payment-soak-*.jsonl")):
        for line in f.read_text().splitlines():
            try:
                rec = json.loads(line)
            except json.JSONDecodeError:
                continue
            reader = _reader_key(rec.get("reader", ""))
            wallet = rec.get("wallet", "cashu_me")
            cell = cells.setdefault((wallet, reader),
                                    {"ok": 0, "fail": 0, "evidence": []})
            cell["ok" if rec.get("ok") else "fail"] += 1
            if f.name not in cell["evidence"]:
                cell["evidence"].append(f.name)
    return cells


def render(cells: dict[tuple[str, str], dict]) -> str:
    readers = sorted({r for _, r in cells} | set(READER_FOR.values()))
    wallets = sorted({w for w, _ in cells})
    lines = [
        "# cashu-nfc-matrix — proven cells",
        "",
        "GENERATED by bench/render_matrix.py — do not edit by hand;",
        "every cell cites its evidence file(s).",
        "",
        "| wallet | " + " | ".join(readers) + " |",
        "|---" * (len(readers) + 1) + "|",
    ]
    for w in wallets:
        row = [w]
        for r in readers:
            c = cells.get((w, r))
            if not c:
                row.append("—")
            elif c["fail"] == 0:
                row.append(f"**{c['ok']} ok** ({c['evidence'][0]})")
            else:
                row.append(f"{c['ok']} ok / {c['fail']} fail ({c['evidence'][0]})")
        lines.append("| " + " | ".join(row) + " |")
    lines.append("")
    return "\n".join(lines)


def refresh_readme(md: str) -> None:
    if not README.exists():
        return
    t = README.read_text()
    block = ("<!-- matrix:begin (generated) -->\n" + md
             + "<!-- matrix:end -->")
    if "<!-- matrix:begin" in t:
        t = re.sub(r"<!-- matrix:begin.*?<!-- matrix:end -->",
                   block, t, flags=re.S)
    else:
        t += "\n\n" + block + "\n"
    README.write_text(t)


def main() -> int:
    cells = collect()
    md = render(cells)
    out = RESULTS / "MATRIX.md"
    RESULTS.mkdir(exist_ok=True)
    out.write_text(md)
    print(md)
    if "--readme" in __import__("sys").argv:
        refresh_readme(md)
        print(f"\nREADME block refreshed: {README}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
