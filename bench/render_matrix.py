#!/usr/bin/env python3
"""Render the wallet matrix (refactor 3) from results/*.jsonl evidence.

Reads every results/payment-soak-*.jsonl and emits results/MATRIX.md — a
per-(wallet, reader) table of what has been PROVEN, with evidence links.
Hand-edited matrix rows are retired: the README block is regenerated from
the same data with --readme.

Usage:
  python3 bench/render_matrix.py               # results/MATRIX.md
  python3 bench/render_matrix.py --readme      # + refresh README block

Deterministic, offline, no hardware.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
RESULTS = REPO / "results"
README = REPO / "README.md"

READER_FOR = {
    "Nucula": "nucula/PN7160",
    "ACR": "ACR1252",
    "M5stick": "m5stick/MFRC522",
}


def _reader_key(subst: str) -> str:
    for k, v in READER_FOR.items():
        if subst.startswith(k):
            return v
    return subst


def collect() -> dict[tuple[str, str], dict]:
    """cells[(wallet, reader)] -> {ok, fail, evidence:[files]}"""
    cells: dict[tuple[str, str], dict] = {}
    for f in sorted(RESULTS.glob("payment-soak-*.jsonl")):
        for line in f.read_text().splitlines():
            try:
                rec = json.loads(line)
            except json.JSONDecodeError:
                continue
            reader = _reader_key(rec.get("reader", ""))
            wallet = rec.get("wallet", "cashu_me")
            cell = cells.setdefault((wallet, reader),
                                    {"ok": 0, "fail": 0, "evidence": []})
            cell["ok" if rec.get("ok") else "fail"] += 1
            if f.name not in cell["evidence"]:
                cell["evidence"].append(f.name)
    return cells


def render(cells: dict[tuple[str, str], dict]) -> str:
    readers = sorted({r for _, r in cells} | set(READER_FOR.values()))
    wallets = sorted({w for w, _ in cells})
    lines = [
        "# cashu-nfc-matrix — proven cells",
        "",
        "GENERATED by bench/render_matrix.py — do not edit by hand;",
        "every cell cites its evidence file(s).",
        "",
        "| wallet | " + " | ".join(readers) + " |",
        "|---" * (len(readers) + 1) + "|",
    ]
    for w in wallets:
        row = [w]
        for r in readers:
            c = cells.get((w, r))
            if not c:
                row.append(f"\u26AA — {_staleness_mark_for(w, r)}")
                continue
            mark = "\U0001F7E2" if c["fail"] == 0 else "\U0001F534"
            age_mark = _staleness_mark_for(w, r)
            base = (f"{c['ok']} ok" if c["fail"] == 0
                    else f"{c['ok']} ok / {c['fail']} fail")
            row.append(f"{mark} {base} {age_mark} ({c['evidence'][0]})")
        lines.append("| " + " | ".join(row) + " |")
    lines.append("")
    return "\n".join(lines)


def refresh_readme(md: str) -> None:
    if not README.exists():
        return
    t = README.read_text()
    block = ("<!-- matrix:begin (generated) -->\n" + md
             + "<!-- matrix:end -->")
    if "<!-- matrix:begin" in t:
        t = re.sub(r"<!-- matrix:begin.*?<!-- matrix:end -->",
                   block, t, flags=re.S)
    else:
        t += "\n\n" + block + "\n"
    README.write_text(t)


def _staleness_mark_for(wallet: str, reader: str) -> str:
    """Age emoji from registry max-age vs newest matching evidence file."""
    try:
        import time as _t
        import yaml
        reg = yaml.safe_load(
            (REPO / "matrixctl" / "registry.yaml").read_text())["cells"]
    except Exception:
        return ""
    reader_key = {"nucula/PN7160": "nucula", "ACR1252": "acr",
                  "m5stick/MFRC522": "m5stick"}.get(reader, "")
    ma = None
    for name, c in reg.items():
        if reader_key and reader_key in name:
            ma = c.get("max_age_d")
    if ma is None:
        return "\u26AA"  # white: no budget (opportunistic)
    newest = 0.0
    for f in RESULTS.glob("payment-soak-*.jsonl"):
        import re as _re
        m = _re.match(r"payment-soak-(\d{8}-\d{6})\.jsonl", f.name)
        if m:
            newest = max(newest, _t.mktime(
                _t.strptime(m.group(1), "%Y%m%d-%H%M%S")))
    if not newest:
        return "\U0001F7E0"  # orange: never proven
    age_d = (_t.time() - newest) / 86400.0
    return ("\U0001F534" if age_d > ma
            else "\U0001F7E1" if age_d > ma / 2 else "\U0001F7E2")


def _staleness_mark(cell_hint: str) -> str:
    """Fresh/aging/stale mark from registry max-age vs last evidence."""
    try:
        import yaml
        reg = yaml.safe_load(
            (REPO / "matrixctl" / "registry.yaml").read_text())["cells"]
    except Exception:
        return ""
    # map evidence reader back to registry cell names (best-effort)
    for name, c in reg.items():
        if cell_hint and cell_hint in name:
            age = __import__("matrixctl.next", fromlist=["next"]) \
                .last_evidence_age_d(name)
            if age is None:
                return " (never)"
            ma = c.get("max_age_d")
            if ma is None:
                return ""
            return " (stale!)" if age > ma else " (fresh)" if age < ma / 2 else " (aging)"
    return ""


def main() -> int:
    cells = collect()
    md = render(cells)
    out = RESULTS / "MATRIX.md"
    RESULTS.mkdir(exist_ok=True)
    out.write_text(md)
    print(md)
    if "--readme" in __import__("sys").argv:
        refresh_readme(md)
        print(f"\nREADME block refreshed: {README}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
